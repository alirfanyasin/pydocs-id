/* eslint-disable @typescript-eslint/no-require-imports -- CommonJS loader for chapter TypeScript files. */
// Regenerate with: python -m pip install matplotlib && node scripts/generate-matplotlib-previews.cjs
const fs = require("node:fs");
const path = require("node:path");
const { spawnSync } = require("node:child_process");
const ts = require("typescript");

require.extensions[".ts"] = (mod, filename) => {
  mod._compile(ts.transpileModule(fs.readFileSync(filename, "utf8"), {
    compilerOptions: { module: ts.ModuleKind.CommonJS },
  }).outputText, filename);
};
const chapters = fs.readdirSync("app/data/matplotlib-chapters").flatMap(filename =>
  Object.values(require(path.resolve("app/data/matplotlib-chapters", filename))),
);
const programs = chapters.flatMap(doc => [
  ...doc.examples.map(item => ({ id: item.id, code: item.code })),
  ...[...(doc.codingChallenges || []), ...(doc.caseStudies || [])].map(item => ({ id: item.id, code: item.solutionCode })),
]);
const result = spawnSync("python", ["-c", `
import sys, json, hashlib, io, contextlib
from pathlib import Path
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
destination = Path("public/matplotlib")
destination.mkdir(parents=True, exist_ok=True)
previews, cache = {}, {}
for item in json.load(sys.stdin):
    digest = hashlib.sha256(item["code"].encode()).hexdigest()[:16]
    if digest not in cache:
        with contextlib.redirect_stdout(io.StringIO()):
            exec(compile(item["code"], item["id"], "exec"), {})
        cache[digest] = []
        for index, number in enumerate(plt.get_fignums()[:4]):
            filename = digest + "-" + str(index + 1) + ".png"
            plt.figure(number).savefig(destination / filename, format="png", dpi=110, bbox_inches="tight")
            cache[digest].append("/matplotlib/" + filename)
        plt.close("all")
    previews[item["id"]] = cache[digest]
print(json.dumps(previews, indent=2))
`], { input: JSON.stringify(programs), encoding: "utf8", maxBuffer: 2_000_000 });
if (result.status !== 0) throw new Error(result.error?.message || result.stderr || "Gagal membuat pratinjau grafik");
fs.writeFileSync("app/data/matplotlib-previews.ts", "// Generated by scripts/generate-matplotlib-previews.cjs\nexport const MATPLOTLIB_PREVIEWS: Record<string, string[]> = " + result.stdout.trim() + ";\n");
console.log(`Pratinjau siap untuk ${programs.length} contoh dan latihan.`);
